import {
  ARTICLES_INDEX_KEY,
  FOTOS_INDEX_KEY,
  FOTOS_PREFIX,
  deleteObjectFromR2,
  readJsonFromR2,
  writeJsonToR2,
} from "@/lib/r2";

export interface FotoGaleria {
  id: string;
  url: string;
  key: string;
  titulo: string;
  legenda: string;
  localSlug: string;
  localNome: string;
  destaque: boolean;
  createdAt: string;
}

export interface ArtigoBlog {
  id: string;
  title: string;
  summary: string;
  category: string;
  coverImage?: string;
  content: string;
  markdown?: string;
  tags?: string[];
  publishedAt: string;
  status: "published" | "draft";
  featured?: boolean;
  autoGenerated?: boolean;
}

export const LOCAIS_AQUIRAZ = [
  { slug: "porto-das-dunas", nome: "Porto das Dunas" },
  { slug: "prainha-e-rendeiras", nome: "Prainha & Centro das Rendeiras" },
  { slug: "praia-do-presidio", nome: "Praia do Presídio" },
  { slug: "praia-do-iguape", nome: "Praia do Iguape" },
  { slug: "praia-do-batoque", nome: "Reserva do Batoque" },
  { slug: "centro-historico", nome: "Centro Histórico (1699)" },
  { slug: "foz-do-rio-pacoti", nome: "Foz do Rio Pacoti" },
  { slug: "aquiraz-geral", nome: "Aquiraz · Litoral & Cultura" },
] as const;

export function nomeDoLocal(slug: string): string {
  return LOCAIS_AQUIRAZ.find((l) => l.slug === slug)?.nome || "Aquiraz · Ceará";
}

export async function getFotos(localSlug?: string): Promise<FotoGaleria[]> {
  const list = await readJsonFromR2<FotoGaleria[]>(FOTOS_INDEX_KEY, []);
  const sorted = [...list].sort(
    (a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime()
  );
  if (localSlug && localSlug !== "todos") {
    return sorted.filter((f) => f.localSlug === localSlug);
  }
  return sorted;
}

export async function addFoto(foto: FotoGaleria): Promise<FotoGaleria[]> {
  const list = await readJsonFromR2<FotoGaleria[]>(FOTOS_INDEX_KEY, []);
  const updated = [foto, ...list.filter((f) => f.id !== foto.id)];
  await writeJsonToR2(FOTOS_INDEX_KEY, updated);
  return updated;
}

export async function updateFoto(
  id: string,
  patch: Partial<Pick<FotoGaleria, "titulo" | "legenda" | "localSlug" | "localNome" | "destaque">>
): Promise<FotoGaleria | null> {
  const list = await readJsonFromR2<FotoGaleria[]>(FOTOS_INDEX_KEY, []);
  const idx = list.findIndex((f) => f.id === id);
  if (idx === -1) return null;
  const current = list[idx];
  const nextLocalSlug = patch.localSlug ?? current.localSlug;
  const updatedFoto: FotoGaleria = {
    ...current,
    ...patch,
    localSlug: nextLocalSlug,
    localNome: patch.localNome ?? nomeDoLocal(nextLocalSlug),
  };
  list[idx] = updatedFoto;
  await writeJsonToR2(FOTOS_INDEX_KEY, list);
  return updatedFoto;
}

export async function deleteFoto(id: string): Promise<boolean> {
  const list = await readJsonFromR2<FotoGaleria[]>(FOTOS_INDEX_KEY, []);
  const target = list.find((f) => f.id === id);
  if (!target) return false;
  if (target.key && target.key.startsWith(FOTOS_PREFIX)) {
    await deleteObjectFromR2(target.key);
  }
  const updated = list.filter((f) => f.id !== id);
  await writeJsonToR2(FOTOS_INDEX_KEY, updated);
  return true;
}

export async function getArticles(onlyPublished = true): Promise<ArtigoBlog[]> {
  const list = await readJsonFromR2<ArtigoBlog[]>(ARTICLES_INDEX_KEY, []);
  const filtered = onlyPublished
    ? list.filter((a) => a.status === "published")
    : list;
  return [...filtered].sort(
    (a, b) => new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime()
  );
}

export async function getArticleById(
  id: string,
  includeDraft = false
): Promise<ArtigoBlog | null> {
  const list = await readJsonFromR2<ArtigoBlog[]>(ARTICLES_INDEX_KEY, []);
  const found = list.find((a) => a.id === id);
  if (!found) return null;
  if (!includeDraft && found.status !== "published") return null;
  return found;
}

export async function upsertArticle(article: ArtigoBlog): Promise<ArtigoBlog[]> {
  const list = await readJsonFromR2<ArtigoBlog[]>(ARTICLES_INDEX_KEY, []);
  const updated = [article, ...list.filter((a) => a.id !== article.id)];
  await writeJsonToR2(ARTICLES_INDEX_KEY, updated);
  return updated;
}

export async function deleteArticle(id: string): Promise<boolean> {
  const list = await readJsonFromR2<ArtigoBlog[]>(ARTICLES_INDEX_KEY, []);
  const next = list.filter((a) => a.id !== id);
  if (next.length === list.length) return false;
  await writeJsonToR2(ARTICLES_INDEX_KEY, next);
  return true;
}
